import assert from "node:assert/strict";
import { createNoaaWaveCache } from "../src/noaa-wave-cache.mjs";
import test from "node:test";
test("NOAA cache: validacao e estados", () => {
  const clock = Date.UTC(2026, 9, 24, 7);
  const cache = createNoaaWaveCache({ now: () => clock });
  assert.equal(cache.read().state, "UNAVAILABLE");
  assert.equal(cache.read().snapshot, null);
  const sample = { waveHeightM: 2, units: "m", nature: "MODELO",
    latitude: -23.5, longitude: -43 };
  sample.issuedAt = new Date(clock - 3600000).toISOString();
  sample.validAt = new Date(clock).toISOString();
  sample.expiresAt = new Date(clock + 3600000).toISOString();
  sample.checkedAt = new Date(clock).toISOString();
  sample.sourceUrl = "https://nomads.ncep.noaa.gov/";
  cache.recordSuccess(sample);
  assert.equal(cache.read().state, "CURRENT");
  sample.waveHeightM = 99;
  assert.equal(cache.read().snapshot.waveHeightM, 2);
  cache.read().snapshot.waveHeightM = 88;
  assert.equal(cache.read().snapshot.waveHeightM, 2);
  cache.recordFailure("test_failure");
  assert.equal(cache.read().state, "CURRENT_DEGRADED");
  assert.equal(cache.read().snapshot.waveHeightM, 2);
  assert.equal(cache.read().snapshot.waveHeightM, 2);
  const expiry = Date.parse(sample.expiresAt);
  assert.equal(cache.read({ at: expiry }).state, "STALE");
  assert.equal(cache.read({ at: expiry }).snapshot, null);
  const severe = cache.read({ at: clock + 30000, mode: "severe" });
  assert.equal(severe.refreshDue, true);
  const beforeSevere = cache.read({ at: clock + 29999, mode: "severe" });
  assert.equal(beforeSevere.refreshDue, false);
  const normal = cache.read({ at: clock + 300000, mode: "normal" });
  assert.equal(normal.refreshDue, true);
  const beforeNormal = cache.read({ at: clock + 299999, mode: "normal" });
  assert.equal(beforeNormal.refreshDue, false);
  const past = cache.read({ at: clock - 1 });
  assert.equal(past.state, "UNAVAILABLE");
  assert.equal(past.snapshot, null);
  const invalid = { ...sample, waveHeightM: -1 };
  assert.throws(() => cache.recordSuccess(invalid), /noaa_cache_wave_invalid/);
  cache.recordSuccess({ ...sample, waveHeightM: 2 });
  assert.equal(cache.read().state, "CURRENT");
  assert.equal(cache.read().lastErrorCode, null);
});
